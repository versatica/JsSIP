import * as JsSIP_C from './Constants';
import { Logger } from './Logger';
import { IncomingRequest, IncomingResponse } from './SIPMessage';
import type { IncomingMessage, UALike } from './SIPMessage';
import type { TransactionRegistry } from './Transactions';
import type { Transport } from './Transport';
import * as Utils from './Utils';

const logger = new Logger('sanityCheck');

/**
 * The `UA` surface the sanity checks depend on.
 *
 * TODO: Replace with `import type { UA } from './UA'` once `UA` is ported to
 * TypeScript.
 */
export interface SanityCheckUA extends UALike {
	readonly _transactions: TransactionRegistry;
}

/**
 * A single check. Returns `false` to drop the message, `true` to let it
 * through.
 */
type Check<M extends IncomingMessage> = (
	message: M,
	transport: Transport,
	ua: SanityCheckUA
) => boolean;

// Checks for requests and responses.
const all: Check<IncomingMessage>[] = [minimumHeaders];

// Checks for requests.
const requests: Check<IncomingRequest>[] = [
	rfc3261_8_2_2_1,
	rfc3261_16_3_4,
	rfc3261_18_3_request,
	rfc3261_8_2_2_2,
];

// Checks for responses.
const responses: Check<IncomingResponse>[] = [
	rfc3261_8_1_3_3,
	rfc3261_18_3_response,
];

export const sanityCheck = (
	message: IncomingRequest | IncomingResponse,
	ua: SanityCheckUA,
	transport: Transport
): boolean => {
	for (const check of all) {
		if (!check(message, transport, ua)) {
			return false;
		}
	}

	if (message instanceof IncomingRequest) {
		for (const check of requests) {
			if (!check(message, transport, ua)) {
				return false;
			}
		}
	} else if (message instanceof IncomingResponse) {
		for (const check of responses) {
			if (!check(message, transport, ua)) {
				return false;
			}
		}
	}

	// Everything is OK.
	return true;
};

/*
 * Sanity Check for incoming Messages
 *
 * Requests:
 *  - _rfc3261_8_2_2_1_ Receive a Request with a non supported URI scheme
 *  - _rfc3261_16_3_4_ Receive a Request already sent by us
 *   Does not look at via sent-by but at jssip_id, which is inserted as
 *   a prefix in all initial requests generated by the ua
 *  - _rfc3261_18_3_request_ Body Content-Length
 *  - _rfc3261_8_2_2_2_ Merged Requests
 *
 * Responses:
 *  - _rfc3261_8_1_3_3_ Multiple Via headers
 *  - _rfc3261_18_3_response_ Body Content-Length
 *
 * All:
 *  - Minimum headers in a SIP message
 */

// Sanity Check functions for requests.
function rfc3261_8_2_2_1(
	message: IncomingRequest,
	transport: Transport
): boolean {
	if (message.to.uri.scheme !== 'sip') {
		reply(message, transport, 416);

		return false;
	}

	return true;
}

function rfc3261_16_3_4(
	message: IncomingRequest,
	transport: Transport,
	ua: SanityCheckUA
): boolean {
	if (!message.to_tag) {
		if (message.call_id?.substring(0, 5) === ua.configuration.jssip_id) {
			reply(message, transport, 482);

			return false;
		}
	}

	return true;
}

function rfc3261_18_3_request(
	message: IncomingRequest,
	transport: Transport
): boolean {
	const len = Utils.str_utf8_length(message.body);
	const contentLength = Number(message.getHeader('content-length'));

	if (len < contentLength) {
		reply(message, transport, 400);

		return false;
	}

	return true;
}

function rfc3261_8_2_2_2(
	message: IncomingRequest,
	transport: Transport,
	ua: SanityCheckUA
): boolean {
	const fromTag = message.from_tag;
	const call_id = message.call_id;
	const cseq = message.cseq;

	// Accept any in-dialog request.
	if (message.to_tag) {
		return true;
	}

	// INVITE request.
	if (message.method === JsSIP_C.INVITE) {
		// If the branch matches the key of any IST then assume it is a retransmission
		// and ignore the INVITE.
		// TODO: we should reply the last response.
		// TODO: A Via with no `branch` parameter keys on the literal string
		// 'undefined', so two such requests look like retransmissions of each
		// other. Kept as is to preserve behaviour.
		if (ua._transactions.ist[String(message.via_branch)]) {
			return false;
		}
		// Otherwise check whether it is a merged request.
		else {
			for (const tr of Object.values(ua._transactions.ist)) {
				if (
					tr.request.from_tag === fromTag &&
					tr.request.call_id === call_id &&
					tr.request.cseq === cseq
				) {
					reply(message, transport, 482);

					return false;
				}
			}
		}
	}

	// Non INVITE request.

	// If the branch matches the key of any NIST then assume it is a retransmission
	// and ignore the request.
	// TODO: we should reply the last response.
	else if (ua._transactions.nist[String(message.via_branch)]) {
		return false;
	}

	// Otherwise check whether it is a merged request.
	else {
		for (const tr of Object.values(ua._transactions.nist)) {
			if (
				tr.request.from_tag === fromTag &&
				tr.request.call_id === call_id &&
				tr.request.cseq === cseq
			) {
				reply(message, transport, 482);

				return false;
			}
		}
	}

	return true;
}

// Sanity Check functions for responses.
function rfc3261_8_1_3_3(message: IncomingResponse): boolean {
	if (message.getHeaders('via').length > 1) {
		logger.debug(
			'more than one Via header field present in the response, dropping the response'
		);

		return false;
	}

	return true;
}

function rfc3261_18_3_response(message: IncomingResponse): boolean {
	const len = Utils.str_utf8_length(message.body),
		contentLength = Number(message.getHeader('content-length'));

	if (len < contentLength) {
		logger.debug(
			'message body length is lower than the value in Content-Length header field, dropping the response'
		);

		return false;
	}

	return true;
}

// Sanity Check functions for requests and responses.
function minimumHeaders(message: IncomingMessage): boolean {
	const mandatoryHeaders = ['from', 'to', 'call_id', 'cseq', 'via'];

	for (const header of mandatoryHeaders) {
		if (!message.hasHeader(header)) {
			logger.debug(
				`missing mandatory header field : ${header}, dropping the response`
			);

			return false;
		}
	}

	return true;
}

// Reply.
function reply(
	message: IncomingRequest,
	transport: Transport,
	status_code: number
): void {
	const vias = message.getHeaders('via');

	let response = `SIP/2.0 ${status_code} ${JsSIP_C.REASON_PHRASE[status_code]}\r\n`;

	for (const via of vias) {
		response += `Via: ${via}\r\n`;
	}

	const to = message.getHeader('To');
	const toTag = message.to_tag ? '' : `;tag=${Utils.newTag()}`;

	response += `To: ${to}${toTag}\r\n`;
	response += `From: ${message.getHeader('From')}\r\n`;
	response += `Call-ID: ${message.call_id}\r\n`;
	response += `CSeq: ${message.cseq} ${message.method}\r\n`;
	response += '\r\n';

	transport.send(response);
}
